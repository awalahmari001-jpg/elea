import type { Bilingual } from "@/content/lesson-types";
import type { KidsAgeGroupId } from "./alphabet-phonics-data";

export interface KidsVocabWord {
  id: string;
  word: string;
  emoji: string;
  meaning: Bilingual;
  sentence: string;
  arabicSentence: string;
}

export interface KidsVocabTheme {
  id: string;
  number: number;
  emoji: string;
  ageGroup: KidsAgeGroupId;
  colorClass: string;
  title: Bilingual;
  words: KidsVocabWord[];
}

export interface KidsGrammarQuestion {
  prompt: string;
  emoji: string;
  options: string[];
  correctIndex: number;
  hint: Bilingual;
}

export interface KidsGrammarUnit {
  id: string;
  number: number;
  ageGroup: KidsAgeGroupId;
  emoji: string;
  title: Bilingual;
  pattern: string;
  visualDemo: {
    leftVisual: string;
    leftSentence: string;
    leftArabic: string;
    rightVisual: string;
    rightSentence: string;
    rightArabic: string;
  };
  dialogue: Array<{ speaker: string; emoji: string; line: string }>;
  questions: [KidsGrammarQuestion, KidsGrammarQuestion];
}

function w(
  id: string,
  word: string,
  emoji: string,
  enMeaning: string,
  arMeaning: string,
  sentence: string,
  arabicSentence: string,
): KidsVocabWord {
  return {
    id,
    word,
    emoji,
    meaning: { en: enMeaning, ar: arMeaning },
    sentence,
    arabicSentence,
  };
}

